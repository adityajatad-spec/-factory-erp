/**
 * End-to-end smoke test against a RUNNING Factory ERP (core serving the built web app).
 *
 *   pnpm --filter @factory-erp/web e2e            # BASE_URL defaults to http://127.0.0.1:3000
 *   E2E_SCREENSHOTS=/tmp/shots pnpm --filter @factory-erp/web e2e
 *
 * Journey: login → dashboard → new invoice (keyboard) → issue → PDF generated & downloadable
 * → command palette → mobile layout. Requires seeded demo data (pnpm db:seed).
 */
import { BASE_URL, createChecker, launchBrowser, watchConsole } from './harness';

const { check, steps } = createChecker('smoke');

const browser = await launchBrowser();
try {
  const context = await browser.newContext({
    viewport: { width: 1440, height: 900 },
    locale: 'en-IN',
    timezoneId: 'Asia/Kolkata',
  });
  const page = await context.newPage();
  const consoleErrors = watchConsole(page);

  process.stdout.write(`Factory ERP e2e smoke → ${BASE_URL}\n`);

  await check(
    'signed-out users are sent to login',
    async () => {
      await page.goto(`${BASE_URL}/sales/invoices`);
      await page.waitForURL(/\/login/);
      await page.getByRole('heading', { name: 'Sign in' }).waitFor();
    },
    page,
  );

  await check('wrong password shows an error', async () => {
    await page.getByLabel('Username').fill('accountant');
    await page.getByLabel('Password').fill('wrong-password');
    await page.getByRole('button', { name: 'Sign in' }).click();
    await page.getByRole('alert').filter({ hasText: 'Incorrect username or password' }).waitFor();
  });

  await check(
    'accountant logs in and lands on the dashboard',
    async () => {
      await page.getByLabel('Password').fill('factory-demo');
      await page.getByRole('button', { name: 'Sign in' }).click();
      await page.waitForURL(/\/sales\/invoices/);
      await page.getByRole('link', { name: 'Dashboard' }).first().click();
      await page.getByText("Today's sales").waitFor();
      await page.getByText('Outstanding receivables').waitFor();
      await page.getByText('Recent invoices').waitFor();
    },
    page,
  );

  await check('sidebar only shows functional modules', async () => {
    for (const label of ['Invoices', 'Customers', 'Items & stock'])
      await page.getByRole('link', { name: label }).first().waitFor();
    if ((await page.getByRole('link', { name: 'Production' }).count()) > 0)
      throw new Error('unexpected Production link');
  });

  let invoiceUrl = '';
  await check(
    'create an invoice with the keyboard',
    async () => {
      await page.goto(`${BASE_URL}/sales/invoices/new`);
      const customer = page.getByLabel('Customer');
      await customer.fill('Sharma');
      await page.getByRole('option', { name: /Sharma Components/ }).waitFor();
      await customer.press('Enter');
      const item = page.getByPlaceholder('Search item').first();
      await item.click();
      await item.fill('BA-100');
      await page.getByRole('option', { name: /BA-100/ }).waitFor();
      await item.press('Enter');
      await page.getByLabel('Quantity').first().fill('10');
      await page.getByText('Grand total').first().waitFor();
      // 10 × 245.00 @ 18% = 2891.00 (preview, recomputed by the server on save)
      await page.getByText('₹2,891.00').first().waitFor();
      await page.keyboard.press('Control+Enter');
      await page.waitForURL(/\/sales\/invoices\/[0-9a-f-]{36}$/);
      await page.getByRole('heading', { name: /Draft invoice/ }).waitFor();
      invoiceUrl = page.url();
    },
    page,
  );

  await check(
    'issue the invoice (explicit human confirmation)',
    async () => {
      await page.getByRole('button', { name: 'Issue invoice…' }).click();
      await page.getByRole('dialog').getByText('The invoice becomes permanent').waitFor();
      await page.getByRole('button', { name: /Issue for ₹2,891\.00/ }).click();
      await page.getByRole('heading', { name: /INV\/\d{2}-\d{2}\/\d{5}/ }).waitFor();
    },
    page,
  );

  await check(
    'PDF is generated by the outbox and downloadable',
    async () => {
      const open = page.getByRole('link', { name: 'Open PDF' });
      await open.waitFor({ timeout: 20_000 });
      const href = await open.getAttribute('href');
      const res = await page.request.get(`${BASE_URL}${href ?? ''}`);
      if (res.status() !== 200) throw new Error(`PDF status ${res.status()}`);
      const body = await res.body();
      if (body.subarray(0, 5).toString() !== '%PDF-') throw new Error('not a PDF');
      await page.getByText('Invoice PDF generated').waitFor();
    },
    page,
  );

  await check(
    'command palette finds the invoice',
    async () => {
      await page.keyboard.press('Control+k');
      await page.getByPlaceholder(/Invoice number, customer/).fill('Sharma');
      await page
        .getByRole('option', { name: /INV\/.*Sharma Components/ })
        .first()
        .waitFor();
      await page.keyboard.press('Escape');
    },
    page,
  );

  await check('worker sees no sales data (permission-filtered)', async () => {
    const worker = await browser.newContext({ viewport: { width: 1280, height: 800 } });
    const p = await worker.newPage();
    await p.goto(`${BASE_URL}/login`);
    await p.getByLabel('Username').fill('worker');
    await p.getByLabel('Password').fill('factory-demo');
    await p.getByRole('button', { name: 'Sign in' }).click();
    await p.getByText('No dashboard metrics for your role yet').waitFor();
    if ((await p.getByRole('link', { name: 'Invoices' }).count()) > 0)
      throw new Error('worker can see Invoices');
    await worker.close();
  });

  await check(
    'mobile layout (390 × 844)',
    async () => {
      await page.setViewportSize({ width: 390, height: 844 });
      await page.goto(invoiceUrl);
      await page.getByRole('button', { name: 'Open menu' }).waitFor();
      const overflow = await page.evaluate(
        () => document.documentElement.scrollWidth > window.innerWidth + 1,
      );
      if (overflow) throw new Error('page scrolls horizontally on mobile');
    },
    page,
  );

  await check('no unexpected browser console errors', () => {
    if (consoleErrors.length) throw new Error(consoleErrors.join('\n'));
    return Promise.resolve();
  });

  process.stdout.write(`All ${steps()} smoke checks passed.\n`);
} finally {
  await browser.close();
}
